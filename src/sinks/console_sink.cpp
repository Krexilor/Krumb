// STANDARD HEADERS --------------------------------------------------------------------------------------------------------------------------------|
#include <cstdio>

// PROJECT HEADERS ---------------------------------------------------------------------------------------------------------------------------------|
#include <krumb/sinks/console_sink.hpp>

// CONSOLE SINK ------------------------------------------------------------------------------------------------------------------------------------|
namespace krumb {
    void console_sink::write(std::string_view line) {
        std::fwrite(line.data(), 1, line.size(), stdout);
        std::fputc('\n', stdout);
    }
}
